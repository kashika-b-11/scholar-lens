# 4. PROMPT TEMPLATE UTILITIES
# ==============================================================================

def build_prompt(template: str, **kwargs: Any) -> str:
    """
    Safely formats a prompt template with provided keyword arguments.
    Injects default few-shot exemplars when relevant.
    
    Args:
        template: The string template containing {placeholder} syntax.
        **kwargs: The parameters to populate into the template.
        
    Returns:
        Formatted prompt string ready for LLM API invocation.
    """
    if "few_shot_context" not in kwargs:
        if template == CLAIM_VERIFICATION_PROMPT:
            kwargs["few_shot_context"] = FEW_SHOT_CLAIM_EXTRACTION
        elif template == JARGON_DECODER_PROMPT:
            kwargs["few_shot_context"] = FEW_SHOT_JARGON_EXEMPLAR
        else:
            kwargs["few_shot_context"] = ""
            
    try:
        return template.format(**kwargs)
    except KeyError as e:
        raise ValueError(f"Missing required parameter for prompt template: {e}")
